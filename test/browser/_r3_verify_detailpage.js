// 2026-10-25：图书详情页改造验证（封面/数字卡/同类推荐，与接口同源比对）
const { chromium } = require('playwright');
const BASE = 'http://localhost:5173';
const API = 'http://localhost:8080';
const results = [];
const pass = (n, c, d) => { results.push({ n, c: !!c }); console.log('[' + (c ? 'PASS' : 'FAIL') + '] ' + n + ' ' + (d || '')); };
async function loginRole(page, tid) {
  await page.evaluate(() => localStorage.clear()).catch(() => {});
  await page.goto(BASE + '/login', { waitUntil: 'domcontentloaded' });
  await page.click('[data-testid="' + tid + '"]');
  await page.waitForURL((u) => !u.pathname.endsWith('/login'), { timeout: 10000 });
  await page.waitForTimeout(700);
}
(async () => {
  const browser = await chromium.launch({ args: ['--host-resolver-rules=MAP localhost 127.0.0.1'] });
  const ctx = await browser.newContext();
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', (e) => errs.push(String(e)));
  await loginRole(page, 'quick-login-reader');
  const lg = await page.request.post(API + '/auth/login', { data: { username: 'reader001', password: '123456' } });
  const tok = ((await lg.json()).data || {}).token;
  const b1 = await page.request.get(API + '/books/1', { headers: { token: tok } });
  const book = ((await b1.json()).data) || {};
  const catId = book.categoryId;
  const sl = await page.request.get(API + '/books?page=1&size=6&categoryId=' + catId, { headers: { token: tok } });
  const sameApi = (((await sl.json()).data) || {}).records || [];
  const expectSame = sameApi.filter((b) => b.id !== book.id).slice(0, 5).map((b) => b.title);
  console.log('接口：book.id=' + book.id + ' categoryId=' + catId + ' 同类数=' + sameApi.length);
  await page.goto(BASE + '/book-detail/1', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2200);
  const coverImg = await page.locator('.hero-cover .book-cover__img').count();
  const coverFallback = await page.locator('.hero-cover .book-cover__fallback').count();
  pass('V1 详情页出现封面（真图或生成封面）', coverImg + coverFallback >= 1, 'img=' + coverImg + ' fallback=' + coverFallback);
  const nums = await page.locator('.hero-stats .stat-num').allTextContents();
  const want = [String(Math.max(0, (book.stock || 0) - (book.reservedCount || 0))), String(book.totalStock), String(book.borrowCount || 0)];
  pass('V2 三个数字卡与接口同源一致', JSON.stringify(nums.map((s) => s.trim())) === JSON.stringify(want), 'ui=' + JSON.stringify(nums.map((s) => s.trim())) + ' api=' + JSON.stringify(want));
  const cat = (await page.locator('.hero-tags .tag-cat').textContent().catch(() => '')) || '';
  const pub = (await page.locator('.hero-tags .hero-pub').textContent().catch(() => '')) || '';
  pass('V3 分类标签与出版社齐备', cat.trim() === (book.categoryName || '未分类') && pub.trim() === (book.publisherName || '—'), 'cat=' + cat.trim() + ' pub=' + pub.trim());
  const meta = await page.locator('.hero-meta .meta-row dt').allTextContents();
  pass('V4 元信息四项齐备（ISBN/出版日期/定价/馆藏位置）', JSON.stringify(meta.map((s) => s.trim())) === JSON.stringify(['ISBN', '出版日期', '定价', '馆藏位置']), JSON.stringify(meta.map((s) => s.trim())));
  const sameUi = await page.locator('[data-testid="same-category-item"] .same-title').allTextContents();
  pass('V5 同类推荐与接口同源一致（且不含自身）', JSON.stringify(sameUi.map((s) => s.trim())) === JSON.stringify(expectSame) && sameUi.every((t) => t.trim() !== book.title), 'ui=' + JSON.stringify(sameUi.map((s) => s.trim())) + ' api=' + JSON.stringify(expectSame));
  const desc = (await page.locator('.sec-text').first().textContent().catch(() => '')) || '';
  pass('V6 简介区块存在且有内容', desc.trim().length > 0, 'len=' + desc.trim().length);
  await page.goto(BASE + '/book-search', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(1800);
  await page.locator('.book-card').first().click();
  await page.waitForTimeout(1200);
  const linkTxt = (await page.locator('[data-testid="detail-open-full"]').textContent().catch(() => '')) || '';
  pass('V7 入口文案已改为中性表述（不再许诺「完整详情」）', linkTxt.indexOf('图书详情页') >= 0 && linkTxt.indexOf('完整详情') < 0, 'text=' + linkTxt.trim());
  pass('V8 全程无 JS 运行时错误', errs.length === 0, errs.slice(0, 2).join(' | ').slice(0, 120));
  await browser.close();
  const bad = results.filter((r) => !r.c);
  console.log('---');
  console.log('合计 ' + results.length + ' 项，通过 ' + (results.length - bad.length) + '，失败 ' + bad.length);
  process.exit(bad.length ? 1 : 0);
})();